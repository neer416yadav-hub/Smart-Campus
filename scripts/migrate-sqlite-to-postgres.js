const fs = require("node:fs");
const path = require("node:path");
const { DatabaseSync } = require("node:sqlite");
const { Pool } = require("pg");

const databaseUrl = process.env.DATABASE_URL;
const overwrite = process.argv.includes("--overwrite");
const sqlitePath =
    process.env.DATABASE_PATH ||
    path.join(__dirname, "..", "data", "smart-campus.sqlite");

if (!databaseUrl) {
    console.error(
        "DATABASE_URL is not set. Use the Supabase Session Pooler connection string."
    );
    process.exit(1);
}

if (!fs.existsSync(sqlitePath)) {
    console.error(`Local SQLite database not found: ${sqlitePath}`);
    process.exit(1);
}

function sslOptions() {
    const hostname = new URL(databaseUrl).hostname;
    if (
        hostname === "localhost" ||
        hostname === "127.0.0.1" ||
        hostname === "::1"
    ) {
        return false;
    }
    return { rejectUnauthorized: false };
}

async function main() {
    const sqlite = new DatabaseSync(sqlitePath, { readOnly: true });
    const pool = new Pool({
        connectionString: databaseUrl,
        max: 2,
        ssl: sslOptions()
    });

    try {
        await pool.query(`
            CREATE TABLE IF NOT EXISTS complaints (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                complaint_id TEXT NOT NULL UNIQUE,
                complaint_json TEXT NOT NULL
            )
        `);
        await pool.query(`
            CREATE TABLE IF NOT EXISTS students (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                roll_key TEXT NOT NULL UNIQUE,
                roll_number TEXT NOT NULL,
                student_name TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                created_at BIGINT NOT NULL
            )
        `);

        const complaints = sqlite
            .prepare("SELECT complaint_id, complaint_json FROM complaints ORDER BY id")
            .all();
        const hasStudentsTable = Boolean(
            sqlite
                .prepare(
                    "SELECT name FROM sqlite_master WHERE type = 'table' AND name = 'students'"
                )
                .get()
        );
        const students = hasStudentsTable
            ? sqlite
                  .prepare(
                      "SELECT roll_key, roll_number, student_name, password_hash, created_at FROM students ORDER BY id"
                  )
                  .all()
            : [];

        let complaintsWritten = 0;
        let studentsWritten = 0;

        const client = await pool.connect();
        try {
            await client.query("BEGIN");

            const complaintSql = overwrite
                ? `INSERT INTO complaints (complaint_id, complaint_json)
                   VALUES ($1, $2)
                   ON CONFLICT (complaint_id)
                   DO UPDATE SET complaint_json = EXCLUDED.complaint_json`
                : `INSERT INTO complaints (complaint_id, complaint_json)
                   VALUES ($1, $2)
                   ON CONFLICT (complaint_id) DO NOTHING`;

            for (const row of complaints) {
                const result = await client.query(complaintSql, [
                    row.complaint_id,
                    row.complaint_json
                ]);
                complaintsWritten += result.rowCount;
            }

            const studentSql = overwrite
                ? `INSERT INTO students (roll_key, roll_number, student_name, password_hash, created_at)
                   VALUES ($1, $2, $3, $4, $5)
                   ON CONFLICT (roll_key)
                   DO UPDATE SET roll_number = EXCLUDED.roll_number,
                                 student_name = EXCLUDED.student_name,
                                 password_hash = EXCLUDED.password_hash,
                                 created_at = EXCLUDED.created_at`
                : `INSERT INTO students (roll_key, roll_number, student_name, password_hash, created_at)
                   VALUES ($1, $2, $3, $4, $5)
                   ON CONFLICT (roll_key) DO NOTHING`;

            for (const row of students) {
                const result = await client.query(studentSql, [
                    row.roll_key,
                    row.roll_number,
                    row.student_name,
                    row.password_hash,
                    row.created_at
                ]);
                studentsWritten += result.rowCount;
            }

            await client.query("COMMIT");
        } catch (error) {
            await client.query("ROLLBACK");
            throw error;
        } finally {
            client.release();
        }

        console.log(`Source:  ${sqlitePath}`);
        console.log(`Found:   ${complaints.length} complaints, ${students.length} students`);
        console.log(
            `Written: ${complaintsWritten} complaints, ${studentsWritten} students` +
                (overwrite ? " (existing rows overwritten)" : " (existing rows skipped)")
        );
    } finally {
        sqlite.close();
        await pool.end();
    }
}

main().catch((error) => {
    console.error("Migration failed:", error.message);
    process.exit(1);
});
